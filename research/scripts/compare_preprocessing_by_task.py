from __future__ import annotations

import argparse
from pathlib import Path
import sys

ROOT_DIR = Path(__file__).resolve().parents[2]
if str(ROOT_DIR) not in sys.path:
    sys.path.insert(0, str(ROOT_DIR))

import numpy as np
import pandas as pd
from sklearn.metrics import accuracy_score, balanced_accuracy_score, f1_score, precision_score, recall_score, roc_auc_score

from research.src.config import CONFIG


DEFAULT_PREDICTIONS = [
    ("natural_multilingual_light", CONFIG.paths.reports_dir / "CSV" / "predictions_attention_bilstm_natural.csv"),
    ("natural_anti_confound", CONFIG.paths.reports_dir / "CSV" / "predictions_attention_bilstm_natural_anti_confound.csv"),
    ("fixed_2s_multilingual_light", CONFIG.paths.reports_dir / "CSV" / "predictions_attention_bilstm_fixed_2s_multilingual_light.csv"),
]


def _safe_auc(y_true: np.ndarray, y_score: np.ndarray) -> float | None:
    try:
        return float(roc_auc_score(y_true, y_score))
    except ValueError:
        return None


def _metrics(frame: pd.DataFrame, group_col: str, profile: str) -> list[dict[str, object]]:
    rows: list[dict[str, object]] = []
    for group_value in sorted(frame[group_col].dropna().astype(str).unique()):
        sub = frame[frame[group_col].astype(str) == group_value]
        y_true = sub["label"].astype(float).astype(int).to_numpy()
        y_score = sub["score_patients"].astype(float).to_numpy()
        y_pred = (sub["pred_label"].astype(str) == "Patients").astype(int).to_numpy()
        n_healthy = int((y_true == 0).sum())
        n_patients = int((y_true == 1).sum())
        fp_count = int(((y_true == 0) & (y_pred == 1)).sum())
        fn_count = int(((y_true == 1) & (y_pred == 0)).sum())
        rows.append(
            {
                "profile": profile,
                "group_col": group_col,
                "group": group_value,
                "n_samples": int(len(sub)),
                "n_subjects": int(sub["subject_id"].nunique()),
                "n_healthy": n_healthy,
                "n_patients": n_patients,
                "accuracy": float(accuracy_score(y_true, y_pred)),
                "balanced_accuracy": float(balanced_accuracy_score(y_true, y_pred)),
                "auc": _safe_auc(y_true, y_score),
                "precision": float(precision_score(y_true, y_pred, zero_division=0)),
                "recall": float(recall_score(y_true, y_pred, zero_division=0)),
                "f1": float(f1_score(y_true, y_pred, zero_division=0)),
                "fp_count": fp_count,
                "fn_count": fn_count,
                "false_positive_rate": fp_count / max(n_healthy, 1),
                "false_negative_rate": fn_count / max(n_patients, 1),
            }
        )
    return rows


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Compare preprocessing profiles by LANNA pronunciation task groups.")
    parser.add_argument(
        "--taxonomy",
        default=str(CONFIG.paths.reports_dir / "CSV" / "pronunciation_audit" / "pronunciation_master_table.csv"),
        help="Pronunciation taxonomy CSV generated by audit_pronunciation_structure.py.",
    )
    parser.add_argument(
        "--output",
        default=str(CONFIG.paths.reports_dir / "CSV" / "preprocessing_by_task_comparison.csv"),
        help="Output comparison CSV.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    taxonomy = pd.read_csv(args.taxonomy)
    taxonomy_cols = ["sample_id", "task_type", "task_group", "syllable_group", "articulatory_complexity"]
    taxonomy = taxonomy[taxonomy_cols].copy()

    rows: list[dict[str, object]] = []
    for profile, pred_path in DEFAULT_PREDICTIONS:
        if not Path(pred_path).exists():
            print(f"Skipping missing predictions: {pred_path}")
            continue
        pred = pd.read_csv(pred_path)
        merged = pred.merge(taxonomy, on="sample_id", how="left", suffixes=("", "_taxonomy"))
        for group_col in ["task_type", "syllable_group", "articulatory_complexity"]:
            rows.extend(_metrics(merged, group_col, profile))

    frame = pd.DataFrame(rows)
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    frame.to_csv(output, index=False)
    print(frame.to_string(index=False))
    print(f"\nSaved: {output}")


if __name__ == "__main__":
    main()
